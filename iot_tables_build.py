def write_table(name, cols, rows, widths=None, wrap_cols=(), freeze="A2"):
    ws = wb.create_sheet(name)
    ws.append(cols)
    for r in rows:
        ws.append(r)
    for i, c in enumerate(cols, start=1):
        cell = ws.cell(row=1, column=i)
        cell.fill = HDR_FILL
        cell.font = HDR_FONT
        cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 30
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row, max_col=len(cols)):
        for cell in row:
            cell.font = BODY_FONT
            cell.border = BORDER
            h = Alignment(vertical="top", wrap_text=(cols[cell.column - 1] in wrap_cols))
            cell.alignment = h
    if widths:
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(cols)), ws.max_row)
    return ws

